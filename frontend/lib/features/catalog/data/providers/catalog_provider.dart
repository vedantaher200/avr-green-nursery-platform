// Dynamic Product Catalog Provider with Tenant Isolation & Nursery Filtering
// ─────────────────────────────────────────────────────────────────────────────
final catalogListProvider = FutureProvider<List<Product>>((ref) async {
  final apiClient = ref.watch(apiClientProvider);
  final selectedNursery = ref.watch(selectedNurseryProvider);

  try {
    final Map<String, dynamic> params = {'limit': 50};
    if (selectedNursery != null) {
      params['tenantId'] = selectedNursery.tenantId;
    }

    final response = await apiClient.dio.get('/products', queryParameters: params);
    if (response.statusCode == 200 && response.data != null) {
      final raw = response.data['data'];
      if (raw is List && raw.isNotEmpty) {
        return raw.map((json) {
          final p = Product.fromJson(json as Map<String, dynamic>);
          if (selectedNursery != null) {
            return Product(
              id: p.id,
              tenantId: selectedNursery.tenantId,
              nurseryName: selectedNursery.name,
              sku: p.sku,
              commonName: p.commonName,
              scientificName: p.scientificName,
              crop: p.crop,
              variety: p.variety,
              sellingUnit: p.sellingUnit,
              traySize: p.traySize,
              trayCapacity: p.trayCapacity,
              minOrderQty: p.minOrderQty,
              description: p.description,
              price: p.price,
              plantPrice: p.plantPrice,
              trayPrice: p.trayPrice,
              bulkPrice: p.bulkPrice,
              costPrice: p.costPrice,
              categoryId: p.categoryId,
              categoryName: p.categoryName,
              images: p.images,
              availableStock: p.availableStock,
              readyStock: p.readyStock,
              futureStock: p.futureStock,
              readyDate: p.readyDate,
              nurseryRating: selectedNursery.rating,
              productRating: p.productRating,
              reviewCount: selectedNursery.reviewCount,
              care: p.care,
              agronomy: p.agronomy,
            );
          }
          return p;
        }).toList();
      }
    }
  } catch (_) {
    // Graceful offline fallback
  }

  // Filter default catalog by selected nursery if set
  if (selectedNursery != null) {
    final matched = defaultBotanicalCatalog
        .where((p) => p.tenantId == selectedNursery.tenantId || p.nurseryName.toLowerCase() == selectedNursery.name.toLowerCase())
        .toList();
    if (matched.isNotEmpty) return matched;
  }

  return defaultBotanicalCatalog;
});

// ─────────────────────────────────────────────────────────────────────────────
// Filtered Catalog for Category → Crop → Variety Browsing
// ─────────────────────────────────────────────────────────────────────────────
final filteredCatalogProvider = Provider<List<Product>>((ref) {
  final catalogAsync = ref.watch(catalogListProvider);
  final selectedCategory = ref.watch(selectedCategoryProvider);
  final selectedCrop = ref.watch(selectedCropProvider);
  final searchQuery = ref.watch(searchQueryProvider).toLowerCase().trim();

  final list = catalogAsync.value ?? defaultBotanicalCatalog;

  return list.where((p) {
    final matchesSearch = searchQuery.isEmpty ||
        p.commonName.toLowerCase().contains(searchQuery) ||
        (p.scientificName?.toLowerCase().contains(searchQuery) ?? false) ||
        p.crop.toLowerCase().contains(searchQuery) ||
        p.variety.toLowerCase().contains(searchQuery) ||
        p.sku.toLowerCase().contains(searchQuery) ||
        p.nurseryName.toLowerCase().contains(searchQuery);

    // 1. Authoritative Crop Filter (Issue #11 & Sections 8, 9, 10)
    // When a specific crop is selected, only that crop's varieties must appear
    if (selectedCrop != 'all') {
      final pCrop = p.crop.toLowerCase().trim();
      final selCrop = selectedCrop.toLowerCase().trim();
      final matchesCrop = pCrop == selCrop || pCrop.contains(selCrop) || p.variety.toLowerCase().contains(selCrop);
      if (!matchesCrop) return false;
      return matchesSearch;
    }

    // 2. Category Filter (Applied when no specific crop is chosen)
    bool matchesCategory = selectedCategory == 'all';
    if (!matchesCategory) {
      final pCat = p.categoryId.toLowerCase();
      final pName = p.categoryName.toLowerCase();
      final sel = selectedCategory.toLowerCase();

      if (sel == 'vegetables') {
        matchesCategory = pCat.contains('veg') || pName.contains('veg') || p.sku.startsWith('VEG') || p.sku.contains('TOM') || p.sku.contains('CHIL') || p.sku.contains('CAP') || p.sku.contains('BRIN') || p.sku.contains('CAB') || p.sku.contains('CAUL') || p.sku.contains('SUG');
      } else if (sel == 'flowers') {
        matchesCategory = pCat.contains('flower') || pName.contains('flower') || p.sku.startsWith('FLW') || p.sku.contains('MAR') || p.sku.contains('ROS') || p.sku.contains('JAS');
      } else if (sel == 'fruits') {
        matchesCategory = pCat.contains('fruit') || pName.contains('fruit') || p.sku.startsWith('FRUIT') || p.sku.contains('MAN') || p.sku.contains('LEM') || p.sku.contains('GUA') || p.sku.contains('COC');
      } else if (sel == 'medicinal') {
        matchesCategory = pCat.contains('med') || pName.contains('med') || p.sku.startsWith('MED') || p.sku.contains('TUL') || p.sku.contains('ALO');
      } else if (sel == 'indoor') {
        matchesCategory = pCat.contains('indoor') || pName.contains('indoor') || p.sku.startsWith('IND') || p.sku.contains('ARE') || p.sku.contains('SNK') || p.sku.contains('MON');
      } else if (sel == 'other') {
        matchesCategory = pCat.contains('other') || pName.contains('other') || p.sku.startsWith('OTH') || p.sku.contains('FERT') || p.sku.contains('TRAY');
      } else {
        matchesCategory = pCat == sel || pName.contains(sel);
      }
    }

    return matchesCategory && matchesSearch;
  }).toList();
});
